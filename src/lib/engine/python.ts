export function wrapPythonScript(
	renderFramePythonFunction: string,
	fps: number = 30,
	title: string = 'asciing.app visualization'
): string {
	const interval = (1 / fps).toFixed(4);

	return `#!/usr/bin/env python3
"""
${title}
Generated by asciing.app — zero-backend generative ASCII studio.
Zero-dependency Python 3 terminal script.
"""

import os
import sys
import time
import math
import shutil

# Enable ANSI escape sequences on Windows cmd.exe / PowerShell
os.system("")

def setup_terminal():
    # Enter alternate screen buffer, hide cursor, and clear screen
    sys.stdout.write("\\033[?1049h\\033[?25l\\033[2J\\033[H")
    sys.stdout.flush()

def restore_terminal():
    # Show cursor, reset colors, and exit alternate screen buffer
    sys.stdout.write("\\033[0m\\033[?25h\\033[?1049l\\n")
    sys.stdout.flush()

${renderFramePythonFunction}

def main():
    setup_terminal()
    start_time = time.time()
    frame_interval = ${interval}

    try:
        while True:
            now = time.time()
            elapsed = now - start_time
            cols, rows = shutil.get_terminal_size(fallback=(80, 24))
            # Reserve 1 row to prevent terminal auto-scroll jitter
            render_rows = max(1, rows - 1)

            # Home cursor (flicker-free frame redraw)
            sys.stdout.write("\\033[H")
            
            # Call preset render function
            frame_str = render_frame(cols, render_rows, elapsed)
            sys.stdout.write(frame_str)
            sys.stdout.flush()

            sleep_duration = frame_interval - (time.time() - now)
            if sleep_duration > 0:
                time.sleep(sleep_duration)

    except KeyboardInterrupt:
        pass
    finally:
        restore_terminal()

if __name__ == "__main__":
    main()
`;
}
